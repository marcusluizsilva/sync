    private void criaTrayIcon() {
        if (!SystemTray.isSupported()) {
            System.out.println("Recurso SystemTray não suportado.");
            return;
        } else {
            System.out.println("Recurso SystemTray suportado!");

            ActionListener exitListener = new ActionListener() {
                public void actionPerformed(ActionEvent e) {
                    System.out.println("Saindo...");
                    System.exit(0);
                }
            };

            ActionListener hideListener = new ActionListener() {
                public void actionPerformed(ActionEvent e) {
                    index.setVisible(false);
                }
            };

            ActionListener showListener = new ActionListener() {
                public void actionPerformed(ActionEvent e) {
                    index.setVisible(true);
                }
            };

            PopupMenu popup = new PopupMenu();
            MenuItem defaultItem = new MenuItem("Sair");
            defaultItem.addActionListener(exitListener);
            MenuItem minimiza = new MenuItem("Minimizar");
            minimiza.addActionListener(hideListener);
            MenuItem show = new MenuItem("Mostrar");
            show.addActionListener(showListener);
            popup.add(minimiza);
            popup.add(show);
            popup.add(defaultItem);

            try {
                trayIcon = new TrayIcon(img, "Sync", popup);
                tray.add(trayIcon);
            } catch (AWTException e) {
                JOptionPane.showMessageDialog(null, "Falha ao iniciar TrayIcon", "F-Sync", JOptionPane.ERROR_MESSAGE);
                System.out.println("TrayIcon não pode ser adicionado.");
                return;
            }
        }

    }

